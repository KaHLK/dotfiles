#!/usr/bin/env bash
# Save all tmux sessions to a restore script.
#   tmux-save.sh [OUT]        default OUT: ~/.local/state/tmux/sessions.sh
#   bash OUT                  restore (existing sessions are skipped)
#
# Per pane: cwd, layout, active/zoom state. Panes created with a command
# (`tmux new-window CMD`) rerun it. A foreground program in a shell pane is
# typed at the prompt; it also runs (Enter) when its name is in TMUX_SAVE_RUN.
# Claude Code panes get `--resume <session id>` (from ~/.claude/sessions).

# printf templates emit literal $vars into the restore script.
# shellcheck disable=SC2016
set -euo pipefail

out=${1:-${XDG_STATE_HOME:-$HOME/.local/state}/tmux/sessions.sh}
run_list=" ${TMUX_SAVE_RUN:-nvim vim vi hx less man htop btop top tail watch} "

tmux has-session 2>/dev/null || { echo "no tmux server" >&2; exit 1; }

q() { printf '%q' "$1"; }

# tmux prints argv joined, double-quoting args with spaces: undo that.
unquote_tmux() {
	local s=$1
	if [[ $s == \"*\" ]]; then
		s=${s:1:${#s}-2}
		s=${s//\\\"/\"}
		s=${s//\\\$/\$}
		s=${s//\\\\/\\}
	fi
	printf '%s' "$s"
}

# Command line of the pane's foreground job, empty if the shell is idle.
fg_cmd() {
	local pid=$1 tpgid
	tpgid=$(ps -o tpgid= -p "$pid" 2>/dev/null | tr -d ' ') || return 0
	[[ -n $tpgid && $tpgid != "$pid" && $tpgid -gt 0 ]] || return 0
	ps -ww -o args= -p "$tpgid" 2>/dev/null | sed 's/[[:space:]]*$//' || true
}

# Live Claude Code sessions by tmux pane id: claude_pane[%id]="pid<TAB>sessionId".
# Keyed by pane, not pgid: claude's process-group leader may be a dead wrapper.
declare -A claude_pane=()
while IFS=$'\t' read -r cpane cpid csid; do
	kill -0 "$cpid" 2>/dev/null && claude_pane[$cpane]="$cpid"$'\t'"$csid"
done < <(
	shopt -s nullglob
	files=("${CLAUDE_CONFIG_DIR:-$HOME/.claude}"/sessions/*.json)
	((${#files[@]})) && jq -r 'select(.tmux and .sessionId) | [(.tmux | sub(".*\\."; "")), .pid, .sessionId] | @tsv' "${files[@]}" 2>/dev/null
	true
)

# Claude command line with resume flags replaced by `--resume ID`.
claude_resume_cmd() {
	local pid=$1 sid=$2 kept=() a skip=0
	read -ra args <<<"$(ps -ww -o args= -p "$pid" 2>/dev/null)"
	((${#args[@]})) || args=(claude)
	for a in "${args[@]}"; do
		if ((skip)); then
			skip=0
			[[ $a == -* ]] || continue
		fi
		case $a in
		-r | --resume | --session-id) skip=1 ;;
		-c | --continue | --fork-session | --resume=* | --session-id=*) ;;
		*) kept+=("$a") ;;
		esac
	done
	printf '%s --resume %s' "${kept[*]}" "$sid"
}

F=$'\t'
emit() {
	printf '#!/usr/bin/env bash\n'
	printf '# generated by tmux-save.sh %s\n' "$(date '+%F %T')"
	printf 'set -u\n\n'

	tmux list-sessions -F '#{session_name}' | while IFS= read -r s; do
		printf 's=%s\n' "$(q "$s")"
		printf 'if tmux has-session -t "=$s" 2>/dev/null; then\n'
		printf '\techo "skip $s: exists" >&2\nelse\n'

		first=1
		tmux list-windows -t "=$s" -F "#{window_index}${F}#{window_name}${F}#{automatic-rename}${F}#{window_layout}${F}#{window_active}${F}#{window_zoomed_flag}${F}#{window_width}${F}#{window_height}" |
			while IFS=$F read -r wi wname wauto wlayout wactive wzoom ww wh; do
				name_arg=""
				[[ $wauto == 1 ]] || name_arg="-n $(q "$wname")"
				wt="\"=\$s:$wi\""
				p=0

				tmux list-panes -t "=$s:$wi" -F "#{pane_id}${F}#{pane_pid}${F}#{pane_active}${F}#{pane_current_path}${F}#{pane_start_command}" |
					while IFS=$F read -r pane pid pactive cwd start; do
						cwd_arg=""
						[[ -n $cwd ]] && cwd_arg="-c $(q "$cwd")"
						start_arg=""
						[[ -n $start ]] && start_arg=$(q "$(unquote_tmux "$start")")

						if ((p == 0)) && ((first)); then
							printf '\tread -r wi p0 < <(tmux new-session -d -P -F %s -s "$s" -x %s -y %s %s %s %s)\n' \
								"'#{window_index} #{pane_id}'" "$ww" "$wh" "$name_arg" "$cwd_arg" "$start_arg"
							printf '\t[ "$wi" = %s ] || tmux move-window -s "=$s:$wi" -t %s\n' "$wi" "$wt"
						elif ((p == 0)); then
							printf '\tp0=$(tmux new-window -d -P -F %s -t %s %s %s %s)\n' \
								"'#{pane_id}'" "$wt" "$name_arg" "$cwd_arg" "$start_arg"
						else
							# split the previous pane so new panes keep saved order
							printf '\tp%d=$(tmux split-window -d -P -F %s -t "$p%d" %s %s)\n' \
								"$p" "'#{pane_id}'" "$((p - 1))" "$cwd_arg" "$start_arg"
							printf '\ttmux select-layout -t %s tiled\n' "$wt"
						fi

						if [[ -z $start ]]; then
							if [[ -n ${claude_pane[$pane]:-} ]]; then
								cmd=$(claude_resume_cmd "${claude_pane[$pane]%%$'\t'*}" "${claude_pane[$pane]#*$'\t'}")
							else
								cmd=$(fg_cmd "$pid")
							fi
							if [[ -n $cmd ]]; then
								printf '\ttmux send-keys -t "$p%d" -l %s\n' "$p" "$(q "$cmd")"
								bin=${cmd%% *}
								bin=${bin##*/}
								[[ $run_list == *" $bin "* ]] && printf '\ttmux send-keys -t "$p%d" Enter\n' "$p"
							fi
						fi
						[[ $pactive == 1 ]] && printf '\tactive_pane=$p%d\n' "$p"
						p=$((p + 1))
					done

				printf '\ttmux select-layout -t %s %s\n' "$wt" "$(q "$wlayout")"
				printf '\ttmux select-pane -t "$active_pane"\n'
				[[ $wzoom == 1 ]] && printf '\ttmux resize-pane -Z -t "$active_pane"\n'
				[[ $wactive == 1 ]] && printf '\tactive_win=%s\n' "$wt"
				first=0
			done

		printf '\ttmux select-window -t "$active_win"\n'
		printf 'fi\n\n'
	done
}

mkdir -p "$(dirname "$out")"
tmp=$(mktemp "$out.XXXXXX")
emit >"$tmp"
chmod +x "$tmp"
mv "$tmp" "$out"
echo "saved $(tmux list-sessions | wc -l | tr -d ' ') sessions -> $out"
